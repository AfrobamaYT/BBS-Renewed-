// Coded by Afrobama/Claude — Custom Shader Clip MVP (Approach C).
// User drops a .fsh file in <gameDir>/config/bbstools/shaders/, runs
// /mas shader install <name>, and we materialise a tiny resource
// pack at <gameDir>/resourcepacks/bbstools-user-shaders/ that
// contains the .fsh + Veil boilerplate JSON + pipeline JSON. User
// enables that resource pack and reloads (F3+T) and their shader
// becomes a regular MAS Post-FX they can toggle via /mas user_<name>.
package com.afrobama.bbstools.client.veil;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;
import net.minecraft.client.Minecraft;

/**
 * Installs a user-supplied fragment shader into a generated resource
 * pack that Veil will pick up on next resource reload. Skips the
 * need to mutate the BBSTools jar at runtime.
 *
 * <p>Layout:</p>
 * <pre>
 * &lt;gameDir&gt;/
 *   config/bbstools/shaders/&lt;name&gt;.fsh        ← user's source
 *   resourcepacks/bbstools-user-shaders/
 *     pack.mcmeta                                ← MC resource-pack manifest
 *     assets/bbstools/pinwheel/
 *       post/user_&lt;name&gt;.json                  ← pipeline definition
 *       shaders/program/user/&lt;name&gt;.fsh        ← installed copy
 *       shaders/program/user/&lt;name&gt;.json       ← shader boilerplate
 * </pre>
 *
 * <p>User workflow:</p>
 * <ol>
 *   <li>Write a .fsh file with the standard MAS uniforms
 *       ({@code DiffuseSampler0}, optional {@code MAS_GameTime},
 *       optional {@code MAS_Intensity}).</li>
 *   <li>Save it to {@code config/bbstools/shaders/&lt;name&gt;.fsh}</li>
 *   <li>Run {@code /mas shader install &lt;name&gt;}</li>
 *   <li>Open Resource-Pack menu → enable "BBSTools User Shaders"</li>
 *   <li>Press F3+T (or restart MC) to reload</li>
 *   <li>Run {@code /mas user_&lt;name&gt; on}</li>
 * </ol>
 */
public final class MASUserShaderInstaller
{
    private static final Logger LOG = LoggerFactory.getLogger("mas/user-shader-installer");

    private static final String PACK_NAME = "bbstools-user-shaders";
    private static final String PACK_MCMETA = "{\n"
        + "  \"pack\": {\n"
        + "    \"pack_format\": 34,\n"
        + "    \"description\": \"BBSTools User Shaders \\u2014 generated by /mas shader install. Place .fsh files in config/bbstools/shaders/.\"\n"
        + "  }\n"
        + "}\n";

    private MASUserShaderInstaller() {}

    public static Path getUserShadersDir()
    {
        return Minecraft.getInstance().gameDirectory.toPath()
            .resolve("config").resolve("bbstools").resolve("shaders");
    }

    public static Path getResourcePackRoot()
    {
        return Minecraft.getInstance().gameDirectory.toPath()
            .resolve("resourcepacks").resolve(PACK_NAME);
    }

    /**
     * List .fsh filenames (without extension) in the user shaders dir.
     */
    public static List<String> listUserShaders()
    {
        List<String> names = new ArrayList<>();
        Path dir = getUserShadersDir();
        if (!Files.isDirectory(dir)) return names;
        try (Stream<Path> stream = Files.list(dir))
        {
            stream.filter(p -> p.getFileName().toString().endsWith(".fsh"))
                  .map(p ->
                  {
                      String n = p.getFileName().toString();
                      return n.substring(0, n.length() - 4);
                  })
                  .forEach(names::add);
        }
        catch (IOException e)
        {
            LOG.warn("listUserShaders failed: {}", e.toString());
        }
        return names;
    }

    /**
     * @return human-readable status string for chat feedback (no
     *         exception-throwing variant; caller decodes by prefix).
     */
    public static String install(String name)
    {
        if (name == null || name.isBlank() || !name.matches("[a-z0-9_]+"))
        {
            return "§c[invalid name — use lowercase letters, digits, underscores only]";
        }

        Path source = getUserShadersDir().resolve(name + ".fsh");
        if (!Files.isRegularFile(source))
        {
            return "§c[no file at " + source + " — create the .fsh first]";
        }

        Path packRoot = getResourcePackRoot();
        try
        {
            Files.createDirectories(packRoot);
            /* pack.mcmeta (only write if missing — don't overwrite user edits) */
            Path mcmeta = packRoot.resolve("pack.mcmeta");
            if (!Files.exists(mcmeta))
            {
                Files.writeString(mcmeta, PACK_MCMETA);
            }

            Path postDir = packRoot.resolve("assets/bbstools/pinwheel/post");
            Path shaderDir = packRoot.resolve("assets/bbstools/pinwheel/shaders/program/user");
            Files.createDirectories(postDir);
            Files.createDirectories(shaderDir);

            /* Copy the .fsh */
            Path fshDest = shaderDir.resolve(name + ".fsh");
            Files.copy(source, fshDest, StandardCopyOption.REPLACE_EXISTING);

            /* Shader boilerplate JSON */
            String shaderJson = "{\n"
                + "  \"vertex\": \"veil:blit_screen\",\n"
                + "  \"fragment\": \"bbstools:user/" + name + "\"\n"
                + "}\n";
            Files.writeString(shaderDir.resolve(name + ".json"), shaderJson);

            /* Pipeline JSON (direct write to minecraft:main, proven pattern) */
            String pipelineJson = "{\n"
                + "  \"stages\": [\n"
                + "    {\n"
                + "      \"type\": \"veil:blit\",\n"
                + "      \"shader\": \"bbstools:user/" + name + "\",\n"
                + "      \"in\": \"minecraft:main\",\n"
                + "      \"clear\": false\n"
                + "    }\n"
                + "  ]\n"
                + "}\n";
            Files.writeString(postDir.resolve("user_" + name + ".json"), pipelineJson);

            LOG.info("Installed user shader '{}' into resource pack at {}", name, packRoot);
            return "§a[installed user shader '" + name + "' — enable resource pack 'BBSTools User Shaders' + F3+T, then /mas user_" + name + " on]";
        }
        catch (IOException e)
        {
            LOG.warn("install({}) failed: {}", name, e.toString(), e);
            return "§c[install failed: " + e.getMessage() + "]";
        }
    }

    /**
     * Write a starter template file if config/bbstools/shaders/ is
     * empty, so first-time users have something to copy from.
     */
    public static String initTemplate()
    {
        try
        {
            Path dir = getUserShadersDir();
            Files.createDirectories(dir);
            Path tpl = dir.resolve("template.fsh");
            if (Files.exists(tpl))
            {
                return "§7[template.fsh already exists at " + tpl + "]";
            }
            Files.writeString(tpl,
                "// MAS user shader template. Save under a unique name (e.g. my_effect.fsh)\n"
                + "// then run /mas shader install my_effect\n"
                + "//\n"
                + "// Standard MAS uniforms:\n"
                + "//   DiffuseSampler0   — input scene texture\n"
                + "//   MAS_GameTime      — seconds since mod load (optional)\n"
                + "//   MAS_Intensity     — user-set 0..3 multiplier (optional)\n"
                + "\n"
                + "uniform sampler2D DiffuseSampler0;\n"
                + "uniform float MAS_GameTime;\n"
                + "uniform float MAS_Intensity;\n"
                + "\n"
                + "in vec2 texCoord;\n"
                + "out vec4 fragColor;\n"
                + "\n"
                + "void main() {\n"
                + "    vec4 src = texture(DiffuseSampler0, texCoord);\n"
                + "    // Demo: oscillate red channel with time\n"
                + "    float wave = 0.5 + 0.5 * sin(MAS_GameTime * 2.0 + texCoord.x * 6.28);\n"
                + "    vec3 col = mix(src.rgb, vec3(src.r, src.g * (1.0 - 0.3 * wave), src.b * (1.0 - 0.3 * wave)), MAS_Intensity);\n"
                + "    fragColor = vec4(col, src.a);\n"
                + "}\n");
            return "§a[wrote template at " + tpl + "]";
        }
        catch (IOException e)
        {
            return "§c[template init failed: " + e.toString() + "]";
        }
    }

}
